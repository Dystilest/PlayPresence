package config

import (
	"fmt"
	"reflect"
	"strings"
	"time"
)

type refRow struct{ key, typ, def, doc string }

// Reference renders docs/configuration.md from the Config struct, its `doc`
// tags and the default values, so the documentation cannot drift.
func Reference() string {
	var rows []refRow
	walk(reflect.TypeOf(Config{}), reflect.ValueOf(Default()), "", &rows)

	var b strings.Builder
	b.WriteString("# Configuration reference\n\n")
	b.WriteString("<!-- Generated by `go run ./internal/config/gen`. Do not edit by hand. -->\n\n")
	b.WriteString("PlayPresence reads one TOML file. Keys you omit keep their default value, and unknown keys are rejected.\n\n")
	b.WriteString("| OS | Default location |\n|---|---|\n")
	b.WriteString("| Windows | `%AppData%\\playpresence\\config.toml` |\n")
	b.WriteString("| Linux | `~/.config/playpresence/config.toml` |\n")
	b.WriteString("| macOS | `~/Library/Application Support/playpresence/config.toml` |\n\n")
	b.WriteString("Credentials (server tokens, optional API keys) are **never** stored in this file: they are kept in the OS credential store. A file containing a token or key field is refused.\n\n")
	b.WriteString("| Key | Type | Default | Description |\n|---|---|---|---|\n")
	for _, r := range rows {
		_, _ = fmt.Fprintf(&b, "| `%s` | %s | %s | %s |\n", r.key, r.typ, r.def, r.doc)
	}
	return b.String()
}

func walk(t reflect.Type, v reflect.Value, prefix string, rows *[]refRow) {
	for i := 0; i < t.NumField(); i++ {
		f := t.Field(i)
		name := f.Tag.Get("toml")
		if name == "" || name == "-" {
			continue
		}
		key := prefix + name
		fv := v.Field(i)

		switch {
		case f.Type.Kind() == reflect.Struct && f.Type != reflect.TypeOf(Duration(0)):
			walk(f.Type, fv, key+".", rows)
		case f.Type.Kind() == reflect.Map:
			walk(f.Type.Elem(), reflect.New(f.Type.Elem()).Elem(), key+".<name>.", rows)
		default:
			*rows = append(*rows, refRow{
				key: key,
				typ: typeName(f.Type),
				def: defaultText(fv),
				doc: f.Tag.Get("doc"),
			})
		}
	}
}

func typeName(t reflect.Type) string {
	switch {
	case t == reflect.TypeOf(Duration(0)):
		return "duration"
	case t.Kind() == reflect.Bool:
		return "boolean"
	case t.Kind() == reflect.Slice:
		return "list of strings"
	default:
		return "string"
	}
}

func defaultText(v reflect.Value) string {
	switch x := v.Interface().(type) {
	case Duration:
		return "`" + time.Duration(x).String() + "`"
	case []string:
		if len(x) == 0 {
			return "empty"
		}
		return "`" + strings.Join(x, "`, `") + "`"
	case bool:
		return fmt.Sprintf("`%t`", x)
	case string:
		if x == "" {
			return "empty"
		}
		return "`" + x + "`"
	}
	return ""
}
